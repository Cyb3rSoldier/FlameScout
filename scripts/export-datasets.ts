/**
 * Export FlameScout catalog + FLEX run-level data to machine-readable files
 * for RAG indexing and ML training.
 *
 * Run:  node scripts/export-datasets.ts
 * Out:  datasets/
 *   flex_table_ix.csv        — 276 ISS droplet tests (ML: kNN regression)
 *   flex_table_ix.json       — same data, JSON array
 *   psi_catalog.json         — 21 investigations, full records (RAG corpus)
 *   psi_catalog_chunks.jsonl — one JSON line per RAG chunk, with metadata
 *   README.md                — provenance + usage
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { FLEX_TESTS, FLEX_SOURCE } from "../src/data/flexTests.ts";
import { EXPERIMENTS } from "../src/data/experiments.ts";
import { SOURCES } from "../src/data/sources.ts";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "datasets");
mkdirSync(out, { recursive: true });

const num = (v: number | null) => (v === null ? "" : String(v));
const csvCell = (v: string | number | null) => {
  const s = v === null ? "" : String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

/* ── 1. FLEX Table IX → CSV + JSON ───────────────────────────── */
const flexHeader = ["id","fuel","pressureKpa","o2","n2","co2","he","d0mm","dExtmm","burningRateMm2s","burnTimeS","end","fig","page","source"];
const flexRows = FLEX_TESTS.map((t) => [
  t.id, t.fuel, num(t.p), String(t.o2), String(t.n2), String(t.co2), String(t.he),
  num(t.d0), num(t.dExt), num(t.rate), num(t.tBurn), t.end, num(t.fig), t.page ?? "", FLEX_SOURCE,
]);
const flexCsv = [flexHeader, ...flexRows].map((r) => r.map(csvCell).join(",")).join("\n");
writeFileSync(join(out, "flex_table_ix.csv"), flexCsv + "\n", "utf8");
writeFileSync(join(out, "flex_table_ix.json"), JSON.stringify(FLEX_TESTS, null, 2), "utf8");

/* ── 2. PSI catalog → JSON ───────────────────────────────────── */
writeFileSync(join(out, "psi_catalog.json"), JSON.stringify(EXPERIMENTS, null, 2), "utf8");
writeFileSync(join(out, "psi_sources.json"), JSON.stringify(SOURCES, null, 2), "utf8");

/* ── 3. RAG chunks → JSONL ───────────────────────────────────── */
const percent = (v: number | null) => (v === null ? "—" : `${v}%`);
const kpa = (v: number | null) => (v === null ? "—" : `${v} kPa`);
const conditions = (e: (typeof EXPERIMENTS)[number]) =>
  `Fuel: ${e.fuel}. Atmosphere: ${percent(e.oxygen)} O2 at ${kpa(e.pressure)}. Gravity: ${e.gravity}. Airflow: ${e.airflow}.`;

const chunks: object[] = [];
const push = (id: string, meta: Record<string, unknown>, text: string) => {
  if (!text.trim()) return;
  chunks.push({ id, text: text.replace(/\s+/g, " ").trim(), metadata: meta });
};

for (const e of EXPERIMENTS) {
  const base = {
    experimentId: e.id, sourceId: e.sourceId, title: e.title,
    fuel: e.fuel, oxygen: e.oxygen, pressure: e.pressure, gravity: e.gravity,
    project: e.project ?? null, fireFocus: e.fireFocus ?? null, evidenceStrength: e.evidenceStrength,
  };
  push(`${e.id}::overview`, { ...base, chunkType: "overview" },
    `${e.title} (${e.id}). Objective: ${e.objective ?? ""} Outcome: ${e.outcome ?? ""} ${conditions(e)}${e.hardware ? ` Hardware: ${e.hardware}.` : ""}${e.years ? ` Years: ${e.years}.` : ""}`);
  for (const [i, f] of (e.keyFindings ?? []).entries()) {
    push(`${e.id}::finding-${i + 1}`, { ...base, chunkType: "keyFinding" }, `${e.title} — published finding: ${f}`);
  }
  if (e.variables?.length || e.measurements?.length) {
    push(`${e.id}::method`, { ...base, chunkType: "method" },
      `${e.title} variables swept: ${(e.variables ?? []).join("; ")}. Measurements recorded: ${(e.measurements ?? []).join("; ")}. ${conditions(e)}`);
  }
  if (e.materials?.length) {
    push(`${e.id}::materials`, { ...base, chunkType: "materials" },
      `${e.title} materials/samples tested: ${e.materials.join("; ")}.`);
  }
}

writeFileSync(join(out, "psi_catalog_chunks.jsonl"), chunks.map((c) => JSON.stringify(c)).join("\n") + "\n", "utf8");

/* ── 4. README with provenance ───────────────────────────────── */
writeFileSync(join(out, "README.md"), `# FlameScout datasets (exported from src/data)

Generated by \`node scripts/export-datasets.ts\`. Provenance and honesty rules:

## flex_table_ix.csv / .json
REAL run-level data: **NASA/TP-2015-216046**, "Detailed Results from the Flame
Extinguishment Experiment (FLEX), March 2009 to December 2011", **Table IX**
(${FLEX_TESTS.length} ISS droplet tests). Source: https://ntrs.nasa.gov/citations/20150023456

- ML features: fuel, pressureKpa, o2, n2, co2, he, d0mm
- ML targets: burningRateMm2s, dExtmm, burnTimeS
- Empty cell = missing in the source (never guessed). Do not impute silently.
- Do NOT train/answer outside the tested envelope: pressure 45–320 kPa, O2 12–34%,
  droplet 1–5 mm, fuels {methanol, heptane}. Microgravity droplets only — says
  nothing about solids, spread, or partial gravity.

## psi_catalog.json / psi_sources.json
Summarized catalog of ${EXPERIMENTS.length} NASA microgravity combustion investigations
surfaced through the Physical Sciences Informatics (PSI) database — https://psi.nasa.gov
Values marked approximate in the app (≈ / oxygenNote / pressureNote) remain
approximate here. No safe/unsafe claims.

## psi_catalog_chunks.jsonl
${chunks.length} retrieval chunks for RAG indexing. One JSON object per line:
{ "id", "text", "metadata": { experimentId, sourceId, chunkType, ... } }
chunkType ∈ overview | keyFinding | method | materials

Suggested pipeline: embed "text" (all-MiniLM-L6-v2 or text-embedding-3-small),
store in Chroma/FAISS with metadata, retrieve top-k, answer with citations by
experimentId/sourceId, refuse when retrieval confidence is low.
`, "utf8");

console.log(`FLEX tests exported: ${FLEX_TESTS.length}`);
console.log(`Experiments exported: ${EXPERIMENTS.length}`);
console.log(`RAG chunks written: ${chunks.length}`);
